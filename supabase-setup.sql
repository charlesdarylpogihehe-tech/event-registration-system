create policy "Student reads own profile" on public.student_profiles for select to authenticated using(id=auth.uid());
create policy "Admin reads student profiles" on public.student_profiles for select to authenticated using(public.is_admin());
create policy "Admin reads own admin record" on public.admin_accounts for select to authenticated using(id=auth.uid());
create policy "Events visible to everyone" on public.events for select to anon,authenticated using(true);
create policy "Admins create events" on public.events for insert to authenticated with check(public.is_admin());
create policy "Admins update events" on public.events for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy "Admins delete events" on public.events for delete to authenticated using(public.is_admin());
create policy "Registrations visible to owner or admin" on public.registrations for select to authenticated using(user_id=auth.uid() or public.is_admin());
create policy "Students cancel own registrations" on public.registrations for delete to authenticated using(user_id=auth.uid() and public.is_student());

-- Existing admins may authorize a pre-created Auth identity. The target Auth user must
-- first be created in Supabase Dashboard > Authentication > Users.
create or replace function public.add_admin_by_email(p_email text,p_full_name text default 'Administrator')
returns void language plpgsql security definer set search_path=public,auth as $$
declare target_user auth.users%rowtype;
begin
 if auth.uid() is null or not public.is_admin() then raise exception 'Only an existing administrator can add another administrator.'; end if;
 select * into target_user from auth.users where lower(email)=lower(trim(p_email)) limit 1;
 if target_user.id is null then raise exception 'Create this account in Supabase Authentication > Users first.'; end if;
 insert into public.admin_accounts(id,full_name,email) values(target_user.id,coalesce(nullif(trim(p_full_name),''),'Administrator'),target_user.email)
 on conflict(id) do update set full_name=excluded.full_name,email=excluded.email;
 delete from public.student_profiles where id=target_user.id;
end; $$;
revoke all on function public.add_admin_by_email(text,text) from public;
grant execute on function public.add_admin_by_email(text,text) to authenticated;

create or replace function public.register_for_event(p_event_id bigint)
returns void language plpgsql security definer set search_path=public as $$
declare event_capacity integer; current_count integer;
begin
 if auth.uid() is null or not public.is_student() then raise exception 'Only logged-in student accounts can register for events.'; end if;
 select capacity into event_capacity from public.events where id=p_event_id for update;
 if event_capacity is null then raise exception 'Event not found.'; end if;
 select count(*) into current_count from public.registrations where event_id=p_event_id;
 if current_count>=event_capacity then raise exception 'This event is already full.'; end if;
 insert into public.registrations(user_id,event_id) values(auth.uid(),p_event_id);
end; $$;
revoke all on function public.register_for_event(bigint) from public;
grant execute on function public.register_for_event(bigint) to authenticated;
create or replace function public.get_event_registration_counts()
returns table(event_id bigint,registered_count bigint) language sql stable security definer set search_path=public
as $$ select e.id,count(r.id)::bigint from public.events e left join public.registrations r on r.event_id=e.id group by e.id; $$;
revoke all on function public.get_event_registration_counts() from public;
grant execute on function public.get_event_registration_counts() to anon,authenticated;

