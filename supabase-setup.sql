-- Separate student and administrator account tables for University Event Portal.
-- Back up your project before running. This creates new tables; it does not drop old data.

create table if not exists public.student_profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default 'Student', email text, created_at timestamptz not null default now()
);
create table if not exists public.admin_accounts (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default 'Administrator', email text not null unique,
 created_at timestamptz not null default now()
);
create table if not exists public.events (
 id bigint generated by default as identity primary key, title text not null, description text not null,
 event_date date not null, event_time time not null, location text not null,
 capacity integer not null default 100 check (capacity > 0), created_at timestamptz not null default now()
);
create table if not exists public.registrations (
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.student_profiles(id) on delete cascade,
 event_id bigint not null references public.events(id) on delete cascade,
 registered_at timestamptz not null default now(), unique(user_id,event_id)
);
create index if not exists registrations_event_id_idx on public.registrations(event_id);

-- Every public Auth sign-up receives a student profile only. User metadata cannot grant admin access.
create or replace function public.handle_new_student()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.student_profiles(id,full_name,email)
 values(new.id,coalesce(nullif(trim(new.raw_user_meta_data->>'full_name'),''),'Student'),new.email)
 on conflict(id) do update set full_name=excluded.full_name,email=excluded.email;
 return new;
end; $$;
drop trigger if exists on_auth_user_created_student on auth.users;
create trigger on_auth_user_created_student after insert on auth.users
for each row execute procedure public.handle_new_student();

insert into public.student_profiles(id,full_name,email)
select u.id,coalesce(nullif(trim(u.raw_user_meta_data->>'full_name'),''),'Student'),u.email
from auth.users u where not exists(select 1 from public.admin_accounts a where a.id=u.id)
on conflict(id) do nothing;

-- Migrate existing accounts from the previous single profiles table, if it exists.
do $$ begin
 if to_regclass('public.profiles') is not null then
   execute $q$
     insert into public.student_profiles(id,full_name,email)
     select id,full_name,email from public.profiles where coalesce(role,'student') <> 'admin'
     on conflict(id) do nothing
   $q$;
   execute $q$
     insert into public.admin_accounts(id,full_name,email)
     select id,coalesce(full_name,'Administrator'),coalesce(email,'')
     from public.profiles where role='admin' and email is not null
     on conflict(id) do nothing
   $q$;
 end if;
end $$;
delete from public.student_profiles s where exists(select 1 from public.admin_accounts a where a.id=s.id);

-- Ensure registrations point to student_profiles, including on an existing installation.
do $$ declare c record; begin
 if to_regclass('public.registrations') is not null then
   for c in select conname from pg_constraint
     where conrelid='public.registrations'::regclass and contype='f'
       and pg_get_constraintdef(oid) ilike '%(user_id)%'
   loop execute format('alter table public.registrations drop constraint %I',c.conname); end loop;
   alter table public.registrations
     add constraint registrations_user_id_student_profiles_fkey
     foreign key(user_id) references public.student_profiles(id) on delete cascade;
 end if;
end $$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.admin_accounts where id=auth.uid()); $$;
create or replace function public.is_student()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.student_profiles where id=auth.uid()) and not public.is_admin(); $$;

