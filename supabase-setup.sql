drop policy if exists "Admin reads student profiles" on public.student_profiles;
drop policy if exists "Admin reads own admin record" on public.admin_accounts;
drop policy if exists "Events visible to everyone" on public.events;
drop policy if exists "Admins create events" on public.events;
drop policy if exists "Admins update events" on public.events;
drop policy if exists "Admins delete events" on public.events;
